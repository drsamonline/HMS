#!/usr/bin/env python3
"""Seal a source tree, or check one against its seal.

    python scripts/seal_build.py seal   <tree> --out SEAL.json
    python scripts/seal_build.py verify <tree> --seal SEAL.json

What a seal answers that a provenance mark cannot:

    the mark   proves the code came from here
    the seal   proves the copy is the code that was distributed, unaltered

Both are needed. A copied-and-modified product carries the mark and is not the
product; without a seal, showing that would mean comparing against a release nobody
kept.

The seal is a list of SHA-256 hashes, one per file, plus a digest over the list. It is
deterministic: the same tree always seals to the same digest, so two people can seal
the same release and get the same answer. That is what makes it evidence rather than
a log.

What it does not do: it does not sign. A seal kept in the same repository as the code
can be regenerated by anyone who can edit the code. For a seal to prove anything
against a determined party it has to be published somewhere else - a release page, a
timestamped email, a signed tag. The script says so, because a seal that is trusted
beyond its reach is worse than none.

Exit codes: 0 sealed / verified, 1 differences found, 2 could not run.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

#: Never part of a seal: build output, caches and version control all change without
#: the source changing, and a seal that changes when nothing changed is noise.
EXCLUDED_DIRS = {
    ".git", "__pycache__", "node_modules", ".venv", "venv",
    "dist", "build", ".pytest_cache", ".mypy_cache", ".ruff_cache", "htmlcov",
}
EXCLUDED_FILES = {".DS_Store", "Thumbs.db", "SEAL.json"}
EXCLUDED_SUFFIXES = {".pyc", ".pyo", ".log", ".sqlite3", ".db", ".zip", ".png", ".jpg", ".ico"}

SEAL_VERSION = 1


def _included(path: Path, root: Path) -> bool:
    relative = path.relative_to(root)
    if any(part in EXCLUDED_DIRS for part in relative.parts):
        return False
    if path.name in EXCLUDED_FILES or path.suffix.lower() in EXCLUDED_SUFFIXES:
        return False
    return path.is_file()


def _hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_seal(root: Path) -> dict:
    """The seal for a tree, deterministic in path order."""

    files = sorted(
        str(path.relative_to(root)).replace("\\", "/")
        for path in root.rglob("*")
        if _included(path, root)
    )
    hashes = {name: _hash(root / name) for name in files}

    # A digest over the list, so the manifest itself has one number that can be
    # quoted in a letter or compared over the phone.
    material = json.dumps(hashes, sort_keys=True).encode("utf-8")

    marker = ""
    provenance = root / "backend" / "app" / "core" / "provenance.py"
    if provenance.is_file():
        for line in provenance.read_text(encoding="utf-8").splitlines():
            if line.startswith("RELEASE ="):
                marker = line.split("=", 1)[1].strip().strip('"')

    return {
        "seal_version": SEAL_VERSION,
        "release": marker,
        # Published with the release, not only committed beside it: a seal kept in
        # the same repository as the code can be regenerated by anyone who can edit
        # the code.
        "publish_to": "the release page and the signed tag for this version",
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "file_count": len(hashes),
        "digest": hashlib.sha256(material).hexdigest(),
        "files": hashes,
    }


def compare(seal: dict, root: Path) -> dict:
    """What differs between a seal and a tree."""

    expected = seal.get("files", {})
    actual = {
        str(path.relative_to(root)).replace("\\", "/"): _hash(path)
        for path in root.rglob("*")
        if _included(path, root)
    }

    missing = sorted(set(expected) - set(actual))
    added = sorted(set(actual) - set(expected))
    modified = sorted(
        name for name in set(expected) & set(actual) if expected[name] != actual[name]
    )

    return {
        "missing": missing,
        "added": added,
        "modified": modified,
        "identical": not (missing or added or modified),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Seal a tree, or verify one.")
    parser.add_argument("action", choices=("seal", "verify"))
    parser.add_argument("tree", nargs="?", default=".")
    parser.add_argument("--out", default="SEAL.json")
    parser.add_argument("--seal", default="SEAL.json")
    args = parser.parse_args(argv)

    root = Path(args.tree).resolve()
    if not root.is_dir():
        print(f"{root} is not a directory", file=sys.stderr)
        return 2

    if args.action == "seal":
        seal = build_seal(root)
        Path(args.out).write_text(json.dumps(seal, indent=2, sort_keys=True), encoding="utf-8")
        print(f"sealed {seal['file_count']} files")
        print(f"digest {seal['digest']}")
        return 0

    seal_path = Path(args.seal)
    if not seal_path.is_file():
        print(f"{seal_path} not found", file=sys.stderr)
        return 2

    result = compare(json.loads(seal_path.read_text(encoding="utf-8")), root)
    if result["identical"]:
        print("seal matches: this tree is the one that was sealed")
        return 0

    for label in ("modified", "added", "missing"):
        if result[label]:
            print(f"{label} ({len(result[label])}):")
            for name in result[label][:40]:
                print(f"    {name}")
            if len(result[label]) > 40:
                print(f"    ... and {len(result[label]) - 40} more")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
