#!/usr/bin/env python3
"""Generate the API reference from the live routes.

    python scripts/generate_api_reference.py            # writes docs/API_REFERENCE.md
    python scripts/generate_api_reference.py --check    # fails if the file is stale

The reference is generated rather than written, because a hand-written API document
describes the API somebody meant to build. This one describes the routes that are
mounted right now, with the permission each declares and whether it needs a login.

The output is deterministic - sorted, no timestamps - so a test can regenerate it and
compare. That is the whole point: the moment somebody adds a route without updating
the reference, the build fails rather than the document quietly lying.

Exit codes: 0 written or up to date, 1 stale (with --check), 2 could not run.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

OUTPUT = ROOT / "docs" / "API_REFERENCE.md"

IGNORED_METHODS = {"HEAD", "OPTIONS"}


def _routes():
    """Every mounted route, with what it declares about access."""

    from app.api.v1.api import api_router
    from app.dependencies.permissions import (
        AUTHENTICATED_ONLY_PATHS,
        AUTHENTICATED_ONLY_PREFIXES,
        PUBLIC_PATHS,
        SETUP_PREFIX,
        route_permission,
    )

    rows = []
    for route in api_router.routes:
        path = route.path
        full = path if path.startswith("/api/") else f"/api/v1{path}"
        methods = sorted(
            method.upper()
            for method in (getattr(route, "methods", None) or set())
            if method.upper() not in IGNORED_METHODS
        )
        if not methods:
            continue

        permission = route_permission(route)
        if permission:
            access = f"`{permission}`"
        elif full in PUBLIC_PATHS:
            access = "public"
        elif full.startswith(SETUP_PREFIX):
            access = "setup code"
        elif full in AUTHENTICATED_ONLY_PATHS or full.startswith(AUTHENTICATED_ONLY_PREFIXES):
            access = "login only"
        else:
            access = "**unguarded**"

        response = getattr(route, "response_model", None)
        response_name = getattr(response, "__name__", None) or (
            "list" if response else ""
        )

        rows.append(
            {
                "path": full,
                "methods": methods,
                "access": access,
                "name": getattr(route, "name", ""),
                "response": response_name,
                "tags": sorted(getattr(route, "tags", []) or []),
            }
        )

    return sorted(rows, key=lambda row: (row["path"], row["methods"]))


def render() -> str:
    rows = _routes()
    by_tag: dict[str, list[dict]] = {}
    for row in rows:
        tag = row["tags"][0] if row["tags"] else "Other"
        by_tag.setdefault(tag, []).append(row)

    unguarded = [row for row in rows if row["access"] == "**unguarded**"]

    lines = [
        "# HHMS API reference",
        "",
        "Generated from the mounted routes by `scripts/generate_api_reference.py`.",
        "**Do not edit this file by hand** - a test regenerates it and fails if it",
        "differs, which is how it stays true.",
        "",
        f"{len(rows)} routes across {len(by_tag)} groups.",
        "",
        "## Access",
        "",
        "| Marking | Meaning |",
        "|---|---|",
        "| `permission.code` | The caller must hold this permission |",
        "| login only | A valid token, no particular permission - the caller's own data |",
        "| public | No token at all |",
        "| setup code | The setup wizard, gated by the six-digit code |",
        "| **unguarded** | Nothing guards this route. There should never be one |",
        "",
    ]

    if unguarded:
        lines += ["**Unguarded routes found:**", ""]
        lines += [f"- `{row['path']}`" for row in unguarded]
        lines += [""]

    for tag in sorted(by_tag):
        lines += [f"## {tag}", "", "| Method | Path | Access | Returns |", "|---|---|---|---|"]
        for row in by_tag[tag]:
            methods = ", ".join(row["methods"])
            response = f"`{row['response']}`" if row["response"] else "—"
            lines.append(f"| {methods} | `{row['path']}` | {row['access']} | {response} |")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the API reference.")
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args(argv)

    try:
        content = render()
    except Exception as exc:  # noqa: BLE001 - a generator that cannot run says so
        print(f"could not generate: {exc}", file=sys.stderr)
        return 2

    if args.check:
        if not OUTPUT.is_file():
            print(f"{OUTPUT} does not exist", file=sys.stderr)
            return 1
        if OUTPUT.read_text(encoding="utf-8") != content:
            print(
                f"{OUTPUT} is stale. Run: python scripts/generate_api_reference.py",
                file=sys.stderr,
            )
            return 1
        print("API reference is up to date")
        return 0

    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
