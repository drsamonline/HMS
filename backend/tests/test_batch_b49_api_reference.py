"""Gate for the generated API reference.

A hand-written API document describes the API somebody meant to build. This one
describes the routes mounted right now, and a test regenerates it and compares - so
the moment a route is added without the reference being rebuilt, the build fails
rather than the document quietly lying.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "generate_api_reference.py"
DOC = ROOT / "docs" / "API_REFERENCE.md"


def _generate() -> str:
    """The reference as it would be written now, without touching the file."""

    sys.path.insert(0, str(ROOT / "scripts"))
    import generate_api_reference

    return generate_api_reference.render()


def test_the_reference_exists() -> None:
    assert DOC.is_file()


def test_the_committed_reference_is_current() -> None:
    """The drift gate. Add a route, forget the reference, fail the build."""

    assert DOC.read_text(encoding="utf-8") == _generate(), (
        "docs/API_REFERENCE.md is stale. Run: python scripts/generate_api_reference.py"
    )


def test_the_generator_agrees_with_itself() -> None:
    """Deterministic output is what makes the drift gate possible."""

    assert _generate() == _generate()


def test_every_mounted_route_appears() -> None:
    from app.api.v1.api import api_router

    text = DOC.read_text(encoding="utf-8")
    missing = []
    for route in api_router.routes:
        path = route.path
        full = path if path.startswith("/api/") else f"/api/v1{path}"
        if not (getattr(route, "methods", None) or set()):
            continue
        if full not in text:
            missing.append(full)
    assert not missing, f"routes missing from the reference: {missing}"


def test_the_reference_reports_unguarded_routes_if_there_are_any() -> None:
    """A reference that hides an unguarded route is worse than none."""

    from app.api.v1.api import api_router
    from app.dependencies.permissions import (
        AUTHENTICATED_ONLY_PATHS,
        AUTHENTICATED_ONLY_PREFIXES,
        PUBLIC_PATHS,
        SETUP_PREFIX,
        route_permission,
    )

    unguarded = []
    for route in api_router.routes:
        path = route.path
        full = path if path.startswith("/api/") else f"/api/v1{path}"
        if not (getattr(route, "methods", None) or set()):
            continue
        if route_permission(route) is not None:
            continue
        if full in PUBLIC_PATHS or full.startswith(SETUP_PREFIX):
            continue
        if full in AUTHENTICATED_ONLY_PATHS or full.startswith(AUTHENTICATED_ONLY_PREFIXES):
            continue
        unguarded.append(full)

    text = DOC.read_text(encoding="utf-8")
    if unguarded:
        assert "Unguarded routes found" in text
    else:
        assert "Unguarded routes found" not in text


def test_it_marks_routes_that_need_no_token() -> None:
    text = DOC.read_text(encoding="utf-8")
    assert "| public |" in text
    assert "`/api/v1/health`" in text


def test_it_says_it_must_not_be_edited_by_hand() -> None:
    """Somebody will try. The file should argue with them."""

    text = DOC.read_text(encoding="utf-8")
    assert "Do not edit this file by hand" in text
    assert "scripts/generate_api_reference.py" in text


def test_the_check_mode_fails_on_a_stale_file(tmp_path) -> None:
    """The generator's own check, exercised rather than assumed."""

    stale = tmp_path / "API_REFERENCE.md"
    stale.write_text("# stale\n", encoding="utf-8")

    import generate_api_reference

    original = generate_api_reference.OUTPUT
    try:
        generate_api_reference.OUTPUT = stale
        assert generate_api_reference.main(["--check"]) == 1
    finally:
        generate_api_reference.OUTPUT = original


def test_the_check_mode_passes_on_a_current_file() -> None:
    import generate_api_reference

    assert generate_api_reference.main(["--check"]) == 0


def test_the_script_runs_from_a_shell() -> None:
    """A generator that only works when imported is not a generator."""

    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True
    )
    assert result.returncode == 0, result.stderr
